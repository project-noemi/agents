'use strict';

/**
 * Configuration layers for AGENTS.md (docs/configuration-layers.md).
 *
 * Load order, later wins, missing files are no-ops:
 *   1. AGENTS.md                       upstream baseline
 *   2. each path in AGENTS.layers      (or NOEMI_ORG_LAYERS, comma-separated)
 *   3. AGENTS.local.md                 gitignored, always last
 *
 * `@AGENTS.layers` would only import the list of paths, not the files, so the
 * generator expands the resolved list into explicit `@path` lines inside a
 * marked block in CLAUDE.md / GEMINI.md. With no layer present the block is
 * omitted and the output stays exactly CONTEXT_POINTER (Decision
 * [2026-09-22-0001]). Codex, Cursor and other tools follow the plain-text
 * instruction in the AGENTS.md "Configuration layers" section instead.
 */

const fs = require('fs');
const path = require('path');

const LAYERS_MANIFEST = 'AGENTS.layers';
const LAYERS_MANIFEST_EXAMPLE = 'AGENTS.layers.example';
const LOCAL_LAYER = 'AGENTS.local.md';
const LAYERS_ENV = 'NOEMI_ORG_LAYERS';
const EXAMPLE_LAYER = 'org/example/AGENTS.md';
const HOOK_HEADING = 'Configuration layers';
const BLOCK_BEGIN = '<!-- BEGIN NOEMI CONFIGURATION LAYERS: generated by scripts/generate_all.js from AGENTS.layers / NOEMI_ORG_LAYERS / AGENTS.local.md. Do not edit; re-run `npm run generate`. -->';
const BLOCK_END = '<!-- END NOEMI CONFIGURATION LAYERS -->';

// Names a layer list must never contain: the baseline is always first, the
// local file is always last, and AGENTS.override.md REPLACES the baseline in
// Codex instead of adding to it.
const RESERVED_LAYER_PATHS = new Set(['AGENTS.md', LOCAL_LAYER, 'AGENTS.override.md']);

/**
 * Parse manifest text: one path per line, `#` starts a comment (whole line or
 * after whitespace), blank lines ignored. Returns [{ path, line }].
 */
function parseLayersManifest(text) {
    const entries = [];
    String(text).split(/\r?\n/).forEach((raw, index) => {
        const withoutComment = raw.replace(/(^|\s)#.*$/, '');
        const value = withoutComment.trim();
        if (value) {
            entries.push({ path: value, line: index + 1 });
        }
    });
    return entries;
}

/** Parse NOEMI_ORG_LAYERS. Unset or blank means "use the manifest". */
function parseLayersEnv(value) {
    if (typeof value !== 'string' || value.trim() === '') {
        return null;
    }
    return value.split(',')
        .map((item) => item.trim())
        .filter(Boolean)
        .map((item, index) => ({ path: item, line: index + 1 }));
}

/**
 * Well-formedness of one layer path. Returns an error string or null. Paths
 * must be repo-relative POSIX paths to a .md file that stay inside the repo.
 */
function validateLayerPath(layerPath) {
    if (typeof layerPath !== 'string' || layerPath.length === 0) {
        return 'empty path';
    }
    if (layerPath.startsWith('@')) {
        return 'drop the leading "@": list plain repo-relative paths';
    }
    if (path.posix.isAbsolute(layerPath) || path.win32.isAbsolute(layerPath) || /^[A-Za-z]:/.test(layerPath)) {
        return 'absolute paths are not allowed; use a repo-relative path';
    }
    if (layerPath.startsWith('~')) {
        return 'home-relative paths are not allowed; use a repo-relative path';
    }
    if (layerPath.includes('\\')) {
        return 'use forward slashes';
    }
    if (/\s/.test(layerPath)) {
        return 'whitespace is not allowed (it breaks @path imports)';
    }
    const normalized = path.posix.normalize(layerPath);
    if (normalized === '..' || normalized.startsWith('../') || layerPath.split('/').includes('..')) {
        return '".." segments are not allowed (paths must stay inside the repository)';
    }
    if (!normalized.endsWith('.md')) {
        return 'layer files must be markdown (.md)';
    }
    if (RESERVED_LAYER_PATHS.has(normalized)) {
        return `${normalized} is reserved and cannot be listed as a layer`;
    }
    return null;
}

/** Validate a parsed entry list. Returns [{ line, path, error }]. */
function validateLayerEntries(entries) {
    const errors = [];
    const seen = new Set();
    for (const entry of entries) {
        const error = validateLayerPath(entry.path);
        if (error) {
            errors.push({ ...entry, error });
            continue;
        }
        const normalized = path.posix.normalize(entry.path);
        if (seen.has(normalized)) {
            errors.push({ ...entry, error: 'duplicate entry' });
        }
        seen.add(normalized);
    }
    return errors;
}

/**
 * Resolve the active layer stack for a checkout.
 * Returns { source, declared, present, missing, local, errors } where
 * `present` is the ordered list of layer paths that exist (local excluded).
 */
function resolveLayers({ repoRoot, env = process.env } = {}) {
    let source = 'none';
    let entries = [];

    const fromEnv = parseLayersEnv(env[LAYERS_ENV]);
    const manifestPath = path.join(repoRoot, LAYERS_MANIFEST);
    if (fromEnv) {
        source = LAYERS_ENV;
        entries = fromEnv;
    } else if (fs.existsSync(manifestPath)) {
        source = LAYERS_MANIFEST;
        entries = parseLayersManifest(fs.readFileSync(manifestPath, 'utf8'));
    }

    const errors = validateLayerEntries(entries);
    const declared = entries.map((entry) => path.posix.normalize(entry.path));
    const present = [];
    const missing = [];
    if (errors.length === 0) {
        const realRoot = fs.realpathSync(repoRoot);
        entries.forEach((entry, index) => {
            const layerPath = declared[index];
            const full = path.join(repoRoot, layerPath);
            if (!(fs.existsSync(full) && fs.statSync(full).isFile())) {
                missing.push(layerPath);
                return;
            }
            // A symlink must not smuggle a file from outside the repository.
            const real = fs.realpathSync(full);
            const relative = path.relative(realRoot, real);
            if (relative.startsWith('..') || path.isAbsolute(relative)) {
                errors.push({ ...entry, error: 'resolves (via symlink) outside the repository' });
                return;
            }
            present.push(layerPath);
        });
    }

    const local = fs.existsSync(path.join(repoRoot, LOCAL_LAYER));
    return { source, declared, present, missing, local, errors };
}

/** The marked import block, or '' when there is nothing to import. */
function buildLayerBlock(resolved) {
    const imports = [...resolved.present];
    if (resolved.local) {
        imports.push(LOCAL_LAYER);
    }
    if (imports.length === 0) {
        return '';
    }
    return [BLOCK_BEGIN, ...imports.map((layerPath) => `@${layerPath}`), BLOCK_END, ''].join('\n');
}

/**
 * Full expected content of CLAUDE.md / GEMINI.md: the AGENTS.md pointer,
 * followed by the layer block when any layer resolves.
 */
function buildContextFile({ repoRoot, env = process.env, pointer }) {
    const resolved = resolveLayers({ repoRoot, env });
    if (resolved.errors.length > 0) {
        const detail = resolved.errors
            .map((item) => `  ${resolved.source}:${item.line}: ${item.path} — ${item.error}`)
            .join('\n');
        throw new Error(`Malformed configuration layer path(s):\n${detail}`);
    }
    const block = buildLayerBlock(resolved);
    return { content: block ? `${pointer}\n${block}` : pointer, resolved };
}

/**
 * Light CI contract. Returns a list of failure messages (empty = pass).
 * Missing optional layer files never fail; malformed paths do.
 */
function auditConfigLayers(repoRoot) {
    const failures = [];
    const agentsMd = fs.readFileSync(path.join(repoRoot, 'AGENTS.md'), 'utf8');
    const headings = [...agentsMd.matchAll(/^#\s+(.+)$/gm)].map((match) => match[1].trim());
    if (!headings.includes(HOOK_HEADING)) {
        failures.push(`AGENTS.md is missing the top-level "# ${HOOK_HEADING}" section.`);
    } else {
        if (headings[headings.length - 1] !== HOOK_HEADING) {
            failures.push(`"# ${HOOK_HEADING}" must be the last top-level section of AGENTS.md.`);
        }
        const hook = agentsMd.slice(agentsMd.lastIndexOf(`# ${HOOK_HEADING}`));
        for (const token of [LAYERS_MANIFEST, LAYERS_ENV, LOCAL_LAYER]) {
            if (!hook.includes(token)) {
                failures.push(`AGENTS.md "# ${HOOK_HEADING}" must name \`${token}\`.`);
            }
        }
    }

    if (!fs.existsSync(path.join(repoRoot, EXAMPLE_LAYER))) {
        failures.push(`${EXAMPLE_LAYER} (the layer template) is missing.`);
    }

    for (const manifest of [LAYERS_MANIFEST, LAYERS_MANIFEST_EXAMPLE]) {
        const manifestPath = path.join(repoRoot, manifest);
        if (!fs.existsSync(manifestPath)) {
            continue;
        }
        const errors = validateLayerEntries(parseLayersManifest(fs.readFileSync(manifestPath, 'utf8')));
        for (const item of errors) {
            failures.push(`${manifest}:${item.line}: "${item.path}" — ${item.error}.`);
        }
    }

    const gitignorePath = path.join(repoRoot, '.gitignore');
    const gitignore = fs.existsSync(gitignorePath) ? fs.readFileSync(gitignorePath, 'utf8') : '';
    if (!gitignore.split(/\r?\n/).map((line) => line.trim()).some((line) => line === LOCAL_LAYER || line === `/${LOCAL_LAYER}`)) {
        failures.push(`.gitignore must ignore ${LOCAL_LAYER}.`);
    }

    return failures;
}

module.exports = {
    BLOCK_BEGIN,
    BLOCK_END,
    EXAMPLE_LAYER,
    HOOK_HEADING,
    LAYERS_ENV,
    LAYERS_MANIFEST,
    LAYERS_MANIFEST_EXAMPLE,
    LOCAL_LAYER,
    auditConfigLayers,
    buildContextFile,
    buildLayerBlock,
    parseLayersEnv,
    parseLayersManifest,
    resolveLayers,
    validateLayerEntries,
    validateLayerPath
};
